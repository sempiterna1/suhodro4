// Ветер «Последнего горизонта»: одна сила на всю карту, с порывами. Дует слева направо (по экрану).
// Всё, что реагирует на ветер, берёт его отсюда: снегопад, позёмка, дым, деревья, вымпелы, дымка.
// Без состояния: и сила, и пройденный ветром путь — функции времени, поэтому на паузе ветер не стихает
// и у гостя в коопе всё выглядит так же.

/** Сила ветра 0.25..2: медленные волны + короткие порывы */
export function windAt(t: number): number {
  return Math.max(0.25, 1 + 0.45 * Math.sin(t * 0.23) + 0.35 * Math.sin(t * 0.61 + 1.3) + gustAt(t) * 0.4)
}

/** Короткий порыв 0..1: редкие всплески */
function gustAt(t: number) {
  const g = Math.sin(t * 0.37) * Math.sin(t * 1.13 + 0.7)
  return g > 0.35 ? (g - 0.35) / 0.65 : 0
}

/**
 * Путь, пройденный ветром к моменту t (интеграл силы без порывов, в «секундах ветра»):
 * частицы сдвигаются на speed × windPath(t) — так ускоряются и замедляются плавно, без рывков.
 */
export function windPath(t: number): number {
  return t + (0.45 * (1 - Math.cos(t * 0.23))) / 0.23 + (0.35 * (Math.cos(1.3) - Math.cos(t * 0.61 + 1.3))) / 0.61 + 0.12 * t
}

/** Покачивание в точке x: волна порыва бежит по карте слева направо */
export function swayAt(x: number, t: number): number {
  return windAt(t) * (0.6 + 0.4 * Math.sin(t * 1.7 - x * 0.012))
}
